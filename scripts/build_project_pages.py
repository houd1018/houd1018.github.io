#!/usr/bin/env python3
"""Generate the projects/<slug>.html and professional/<slug>.html page shells.

Every detail page is the same thin shell: header, sketch band with the title, and an
<article id="project-body"> that js/project-page.js fills from <section>/content/<slug>.md.
Run this after adding an entry or changing its title / subtitle / category / year / status in
data/projects.js or data/professional.js.

    python scripts/build_project_pages.py            # write all shells
    python scripts/build_project_pages.py --only sarapist
    python scripts/build_project_pages.py --dry-run
"""
import argparse
import html
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "projects.js"
OUT = ROOT / "projects"
PRO_DATA = ROOT / "data" / "professional.js"
PRO_OUT = ROOT / "professional"

CATEGORY_LABELS = {
    "computer-graphics": "Computer Graphics",
    "tech-art": "Tech Art",
    "games": "Games",
    "creative-coding": "Creative Coding",
}

FIELD_RE = re.compile(r'^\s*([a-zA-Z]+)\s*:\s*(.+?),?\s*$')


def ensure_utf8_stdout() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")


def load_projects(path: Path) -> List[Dict]:
    """Parse the flat `{ key: value, ... }` objects of data/projects.js (values are JSON literals)."""
    projects: List[Dict] = []
    current: Optional[Dict] = None
    for line in path.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if s == "{":
            current = {}
        elif s in ("}", "},") and current is not None:
            projects.append(current)
            current = None
        elif current is not None:
            m = FIELD_RE.match(line)
            if m:
                current[m.group(1)] = json.loads(m.group(2))
    return projects


def render_shell(project: Dict, section: str = "projects") -> str:
    esc = lambda s: html.escape(s or "", quote=True)
    pro = section == "professional"
    if pro:
        label = "Professional"
        sub_text = " · ".join(s for s in (project.get("year"), project.get("status")) if s)
        nav_professional = '<a href="../index.html#professional" aria-current="page">Professional</a>'
        nav_projects = '<a href="../projects/index.html">Projects</a>'
        back = '<a href="../index.html#professional">&larr; All professional work</a>'
    else:
        label = CATEGORY_LABELS.get(project.get("category", ""), project.get("category", ""))
        sub_text = project.get("subtitle") or ""
        nav_professional = '<a href="../index.html#professional">Professional</a>'
        nav_projects = '<a href="index.html" aria-current="page">Projects</a>'
        back = '<a href="index.html">&larr; All projects</a>'
    subtitle = f'\n    <p class="content-subtitle">{esc(sub_text)}</p>' if sub_text else ""
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>{esc(project["title"])} | Dazhou Hou</title>
  <meta name="description" content="{esc(project.get("focus") or project.get("subtitle") or project["title"])}" />
  <script src="../config.js"></script>
  <link rel="icon" href="../assets/img/favicons/favicon.ico" />
  <link rel="stylesheet" href="../css/base.css" />
  <link rel="stylesheet" href="../css/content.css" />
  <link rel="stylesheet"
        href="https://cdn.jsdelivr.net/gh/highlightjs/cdn-release@11.9.0/build/styles/github-dark.min.css"
        integrity="sha384-wH75j6z1lH97ZOpMOInqhgKzFkAInZPPSPlZpYKYTOqsaizPvhQZmAtLcPKXpLyH"
        crossorigin="anonymous" />
</head>
<body class="page-content" data-project="{esc(project["slug"])}">
  <!-- Generated by scripts/build_project_pages.py. Edit {section}/content/{esc(project["slug"])}.md instead. -->
  <a class="skip-link" href="#main">Skip to content</a>

  <header class="site-header">
    <a class="site-brand" href="../index.html">Dazhou Hou</a>
    <nav class="site-nav" aria-label="Primary">
      <a href="../index.html">Home</a>
      <a href="../index.html#about">About Me</a>
      {nav_professional}
      {nav_projects}
      <a href="../blog/index.html">Blog</a>
      <a href="../index.html#contact">Contact</a>
    </nav>
  </header>

  <section class="page-hero content-header" id="hero" data-sketch-mode="static" data-sketch-fit="cover">
    <canvas id="hero-canvas" aria-hidden="true"></canvas>
    <p class="content-category">{esc(label)}</p>
    <h1>{esc(project["title"])}</h1>{subtitle}
  </section>

  <main id="main" class="content content--project" data-defer-enhance>
    <article class="prose" id="project-body" aria-busy="true">
      <noscript><p class="empty-state">This page needs JavaScript to show the content.</p></noscript>
    </article>
    <p class="back-link">{back}</p>
  </main>

  <footer class="site-footer">
    &copy; Dazhou Hou &middot;
    <a href="https://github.com/houd1018" target="_blank" rel="noopener noreferrer">GitHub</a>
  </footer>

  <script src="https://cdn.jsdelivr.net/npm/marked@12.0.2/marked.min.js"
          integrity="sha384-/TQbtLCAerC3jgaim+N78RZSDYV7ryeoBCVqTuzRrFec2akfBkHS7ACQ3PQhvMVi"
          crossorigin="anonymous"></script>
  <script src="https://cdn.jsdelivr.net/npm/dompurify@3.1.6/dist/purify.min.js"
          integrity="sha384-+VfUPEb0PdtChMwmBcBmykRMDd+v6D/oFmB3rZM/puCMDYcIvF968OimRh4KQY9a"
          crossorigin="anonymous"></script>
  <script src="https://cdn.jsdelivr.net/gh/highlightjs/cdn-release@11.9.0/build/highlight.min.js"
          integrity="sha384-F/bZzf7p3Joyp5psL90p/p89AZJsndkSoGwRpXcZhleCWhd8SnRuoYo4d0yirjJp"
          crossorigin="anonymous"></script>
  <script src="../data/projects.js"></script>
  <script src="../data/professional.js"></script>
  <script src="../js/lightbox.js"></script>
  <script src="../js/content.js"></script>
  <script src="../js/project-page.js"></script>
  <script src="../js/hero-sketch.js"></script>
</body>
</html>
"""


def main(argv: Optional[List[str]] = None) -> int:
    ensure_utf8_stdout()
    ap = argparse.ArgumentParser(description="data/projects.js + data/professional.js -> page shells")
    ap.add_argument("--only", help="only write this slug's shell")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)

    written = 0
    for section, data, out_dir in (("projects", DATA, OUT), ("professional", PRO_DATA, PRO_OUT)):
        if not data.is_file():
            continue
        for p in load_projects(data):
            slug = p.get("slug", "")
            if p.get("url") or (args.only and slug != args.only):
                continue
            content = out_dir / "content" / f"{slug}.md"
            note = "" if content.is_file() else f"  [warn] missing {section}/content/{slug}.md"
            print(f"write  {section}/{slug}.html{note}")
            if not args.dry_run:
                out_dir.mkdir(parents=True, exist_ok=True)
                (out_dir / f"{slug}.html").write_text(render_shell(p, section), encoding="utf-8", newline="\n")
                written += 1
    print(f"{written} shells written" if not args.dry_run else "Dry run complete. Nothing was written.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
